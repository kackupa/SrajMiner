import assert from 'node:assert/strict';
import {TileWorld} from '../src/game/world/TileWorld';
import {caveHome,caveClear,caveMove,caveStep,caveSight} from '../src/game/world/CaveHabitat';
import {RockSwimmer} from '../src/game/world/RockSwimmer';
import {snapshotMapState,restoreMapState} from '../src/game/campaign/MapState';
import {WORLD} from '../src/game/config';
const T=WORLD.tile,world=new TileWorld(91,[],[],'cryo-shelf');
const generate=world.generate.bind(world);
world.generate=(x,y)=>({...generate(x,y),type:x>=25&&x<=33&&y>=25&&y<=30?'empty':'rock',ore:undefined});
const home=caveHome(world,2,3)!;assert.ok(home);
assert.deepEqual(caveHome(world,2,3),home,'same seed and geology keep the home fixed');
const inhabitant=new RockSwimmer(91,'cryo-shelf',world);
inhabitant.update(.016,600,home.x+80,home.y);
assert.equal(inhabitant.active?.habitat,home.id,'resident already occupies its cave on approach');
const body={x:home.x,y:home.y,vx:10000,vy:0};
caveMove(world,body,40*T,home.y);
assert.ok(caveClear(world,body.x,body.y),'fast movement cannot tunnel through solid blocks');
assert.ok(body.x<34*T,'wall stops a charge');
const player={x:35.5*T,y:home.y};
assert.equal(caveSight(world,home,player),false);
assert.equal(caveStep(world,home,player),undefined,'sealed chamber has no pursuit path');
for(let x=33;x<=36;x++)world.break(x,Math.floor(home.y/T));
assert.ok(caveStep(world,home,player),'mining a passage connects the habitat');
inhabitant.repel();
const saved=snapshotMapState(undefined,world,home.x,home.y,600,[]);
const restored=restoreMapState(saved,'cryo-shelf',91).world;
assert.ok(restored.clearedCaves.has(home.id),'defeated habitat survives map reload');
const next=new RockSwimmer(91,'cryo-shelf',world);
next.update(1000,600,home.x,home.y);
assert.equal(next.active,undefined,'waiting does not repopulate a cleared cave');
const mined=new TileWorld(92);
for(let x=25;x<34;x++)for(let y=25;y<31;y++)mined.break(x,y);
mined.generate=(x,y)=>({...generate(x,y),type:'rock',ore:undefined});
assert.equal(caveHome(mined,2,3),undefined,'excavation never creates a natural habitat');
console.log('PASS deterministic cave homes, solid walls, fast collision, opened routes and cleared-habitat persistence');

const sealed=new TileWorld(91,[],[],'cryo-shelf');sealed.generate=world.generate;
const charger=new RockSwimmer(91,'cryo-shelf',sealed);
charger.active={kind:'shard-manta',mode:'charge',modeTimer:5,x:home.x,y:home.y,vx:10000,vy:0,life:0,phase:0,health:2,drillCooldown:0,hitFlash:0};
charger.update(.2,600,35.5*T,home.y);
assert.ok(charger.active&&caveClear(sealed,charger.active.x,charger.active.y));
assert.equal(charger.active?.mode,'recover','a charge hitting rock stops and recovers');
const defender=new RockSwimmer(91,'cryo-shelf',sealed);
defender.active={x:home.x,y:home.y,vx:0,vy:0,life:0,phase:0,health:3,drillCooldown:0,hitFlash:0};
let fired=false;
defender.update(.01,600,home.x+40,home.y,[{id:'test',kind:'turret',x:35.5*T,y:home.y}],()=>{fired=true;});
assert.equal(fired,false,'turrets cannot shoot a resident through a sealed cave wall');
console.log('PASS creature charge collision and turret wall occlusion');
