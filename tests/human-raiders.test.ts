import assert from 'node:assert/strict';
import { TileWorld } from '../src/game/world/TileWorld';
import { SurfaceRaid } from '../src/game/world/SurfaceRaid';
import { advanceHuman, type HumanMotion } from '../src/game/world/HumanRaider';
import { HUMAN_RAID, WORLD } from '../src/game/config';
const world=new TileWorld(44,[],[],'cryo-shelf',{columns:126,radiusRows:40});
world.terrain={heights:Array(252).fill(0),caves:[],nests:[]};
const raid=new SurfaceRaid(44,'cryo-shelf'),player={x:680,y:-22};
for(let i=0;i<740;i++)raid.update(.1,true,world,[],undefined,player,true);
assert.equal(raid.active,undefined,'fresh expedition has a grace period');
for(let i=0;i<20;i++)raid.update(.1,true,world,[],undefined,player,true);
assert.equal(raid.active?.human?.kind,'ground');
raid.repel();
for(let i=0;i<1120;i++)raid.update(.1,true,world,[],undefined,player,true);
assert.equal(raid.active?.human?.kind,'gunship','next wave alternates aircraft');
for(let i=0;i<25;i++)raid.update(.1,false,world,[],undefined,player,true);
assert.equal(raid.active,undefined,'tunnels end human attacks');
const body={x:700,y:-22,timer:0,human:{kind:'ground' as const,aimX:0,aimY:0,moving:0,recoil:0,age:0} as HumanMotion};
advanceHuman(body,.1,world,{x:850,y:-22},[]);
assert.ok(body.human.shot,'weapon fires without contact');
assert.equal(body.human.shot!.from.x>body.x,true,'shot originates at aimed barrel');
let impact=false;for(let i=0;i<10;i++)impact ||= !!advanceHuman(body,.1,world,{x:850,y:-22},[]).impact;
assert.ok(impact,'shot has travel time');
const wall={id:'wall',kind:'wall' as const,x:760,y:0};
body.x=700;body.timer=100;
for(let i=0;i<100;i++)advanceHuman(body,.1,world,{x:1100,y:-22},[wall]);
assert.ok(body.x<wall.x-30,'ground attacker stops at a wall');
world.break(18,0);body.x=700;
for(let i=0;i<100;i++)advanceHuman(body,.1,world,{x:1100,y:-22},[]);
assert.ok(body.x<18*WORLD.tile,'ground attacker cannot cross an excavated shaft');
const air={...body,x:700,y:-HUMAN_RAID.altitude,human:{...body.human,kind:'gunship' as const,shot:undefined}};
for(let i=0;i<100;i++)advanceHuman(air,.1,world,{x:1100,y:-22},[wall]);
assert.ok(air.x>wall.x,'gunship flies above walls');assert.ok(air.y< -100);
console.log('PASS human attackers: grace, alternating types, retreat, muzzle, travel, walls, shafts and altitude');
// A projectile resolves against current positions; cover receives the hit first.
const combatWorld=new TileWorld(77,[],[],'cryo-shelf',{columns:126,radiusRows:40});
combatWorld.terrain={heights:Array(252).fill(0),caves:[],nests:[]};
const attacker=()=>({x:700,y:-22,targetId:'player',health:4,timer:0,phase:0,hitFlash:0,drillCooldown:0,human:{kind:'ground' as const,aimX:850,aimY:-22,moving:0,recoil:0,age:0}});
const dodge=new SurfaceRaid(77,'cryo-shelf');dodge.active=attacker();
dodge.update(.01,true,combatWorld,[],undefined,{x:850,y:-22},true);
assert.ok(dodge.active.human?.shot);
assert.equal(dodge.update(.7,true,combatWorld,[],undefined,{x:850,y:-120},true),undefined,'flying out of the shot path dodges damage');
const cover=new SurfaceRaid(77,'cryo-shelf');cover.active=attacker();
const shields=[{id:'cover',kind:'wall' as const,x:780,y:0,integrity:2}];
cover.update(.01,true,combatWorld,shields,undefined,{x:850,y:-22},true);
assert.equal(cover.update(.7,true,combatWorld,shields,undefined,{x:850,y:-22},true)?.type,'damaged');
assert.equal(shields[0].integrity,1,'wall absorbs the bullet instead of the miner');
console.log('PASS human projectiles: dodgeable and blocked by defensive walls');
