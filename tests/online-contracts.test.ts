import assert from 'node:assert/strict';
import { ONLINE_RULESET } from '../src/game/config';
import { conservedCreditMinor, conservedHalfUnits, formatCreditMinor, formatHalfUnits, halfUnitsFromOre, listingHalfUnits, parseNonnegativeSqlInteger, priceMinorFromWholeCredits, tradeTotalMinor, type CreditMinor, type HalfUnits } from '../src/game/online/MarketUnits';
import { parseMarketOperation } from '../src/game/online/Protocol';
import { parseGameCommandBatch } from '../src/game/online/GameProtocol';

const campaign_id = '7b178354-54d0-4ecd-810e-70f422438065';
const operation_id = 'ec509e02-9101-487c-9d69-1cdb6820068d';
const listing_id = '38053ea3-2d77-4dc8-8eb2-59ca54e0a3ba';
const base = { campaign_id, ruleset_version: ONLINE_RULESET, expected_revision: 4, operation_id };
const create = { ...base, command: { kind: 'create_sell_listing', source: 'ship', ore: 'nickel', quantity_half_units: 7, price_credits_per_ore: 19 } };

assert.equal(halfUnitsFromOre(0.5), 1);
assert.equal(halfUnitsFromOre(3.5), 7);
assert.equal(halfUnitsFromOre(0.1), null);
assert.equal(listingHalfUnits(0), null);
assert.equal(listingHalfUnits(2000), 2000);
assert.equal(listingHalfUnits(2001), null);
assert.equal(formatHalfUnits(7 as HalfUnits), '3.5');
assert.equal(priceMinorFromWholeCredits(19), 1900);
assert.equal(priceMinorFromWholeCredits(1.5), null);
assert.equal(priceMinorFromWholeCredits(100001), null);
assert.equal(tradeTotalMinor(1 as HalfUnits, 1900 as CreditMinor), 950);
assert.equal(tradeTotalMinor(7 as HalfUnits, 1900 as CreditMinor), 6650);
assert.equal(tradeTotalMinor(2000 as HalfUnits, 1_000_000 as CreditMinor), 1_000_000_000);
assert.equal(tradeTotalMinor(2000 as HalfUnits, 10_000_000 as CreditMinor), null);
assert.equal(tradeTotalMinor(1 as HalfUnits, 0 as CreditMinor), null);
assert.equal(tradeTotalMinor(1 as HalfUnits, 101 as CreditMinor), null);
assert.equal(formatCreditMinor(6650 as CreditMinor), '66.50');
assert.equal(parseNonnegativeSqlInteger('9007199254740991'), Number.MAX_SAFE_INTEGER);
assert.equal(parseNonnegativeSqlInteger('9007199254740992'), null);
assert.equal(parseNonnegativeSqlInteger('01'), null);
assert.equal(parseNonnegativeSqlInteger(-1), null);

assert.deepEqual(parseMarketOperation(create), create);
assert.equal(parseMarketOperation({ ...create, user_id: campaign_id }), null);
assert.equal(parseMarketOperation({ ...create, command: { ...create.command, balance: 10_000 } }), null);
assert.equal(parseMarketOperation({ ...create, command: { ...create.command, quantity_half_units: 0.5 } }), null);
assert.equal(parseMarketOperation({ ...create, command: { ...create.command, price_credits_per_ore: 100_000, quantity_half_units: 2000 } }), null);
assert.equal(parseMarketOperation({ ...create, ruleset_version: 'local-32' }), null);
assert.equal(parseMarketOperation({ ...create, expected_revision: -1 }), null);
assert.deepEqual(parseMarketOperation({ ...base, command: { kind: 'purchase_listing', listing_id, quantity_half_units: 1, expected_listing_revision: 2, quoted_price_minor: 1900 } })?.command.kind, 'purchase_listing');
assert.equal(parseMarketOperation({ ...base, command: { kind: 'purchase_listing', listing_id, quantity_half_units: 1, expected_listing_revision: 2, quoted_price_minor: 1901 } }), null);
assert.equal(parseMarketOperation({ ...base, command: { kind: 'cancel_listing', listing_id, ore: 'nickel' } }), null);

assert.equal(conservedHalfUnits([10 as HalfUnits, 0 as HalfUnits], [6 as HalfUnits, 4 as HalfUnits]), true);
assert.equal(conservedHalfUnits([10 as HalfUnits], [6 as HalfUnits, 5 as HalfUnits]), false);
assert.equal(conservedHalfUnits([10 as HalfUnits], [12 as HalfUnits], 2), true);
assert.equal(conservedCreditMinor([300 as CreditMinor, 0 as CreditMinor], [150 as CreditMinor, 150 as CreditMinor]), true);
assert.equal(conservedCreditMinor([300 as CreditMinor], [301 as CreditMinor]), false);
const segment = { sequence: 1, duration_ms: 40, left: false, right: false, up: false, down: true, drill: true, aim_cell: { column: 24, row: 2 } };
const batch = { ...base, session_id: listing_id, segments: [segment] };
assert.deepEqual(parseGameCommandBatch(batch), batch);
assert.equal(parseGameCommandBatch({ ...batch, x: 900 }), null);
assert.equal(parseGameCommandBatch({ ...batch, segments: [{ ...segment, ore: 'nickel' }] }), null);
assert.equal(parseGameCommandBatch({ ...batch, segments: [{ ...segment, yield: 100 }] }), null);
assert.equal(parseGameCommandBatch({ ...batch, segments: [{ ...segment, duration_ms: 21 }] }), null);
assert.equal(parseGameCommandBatch({ ...batch, segments: [segment, { ...segment, sequence: 1 }] }), null);
assert.equal(parseGameCommandBatch({ ...batch, segments: Array.from({ length: 5 }, (_, index) => ({ ...segment, sequence: index + 1, duration_ms: 240 })) }), null);
